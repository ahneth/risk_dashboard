// Module-level cache to avoid redundant network fetches per page load
let cacheBundle = null;

/**
 * Loads the entire static JSON cache bundle once per session.
 * @returns {Promise<Object|null>} Parsed JSON object containing series arrays and _meta.
 */
export async function loadFredCache() {
  if (cacheBundle) return cacheBundle;

  try {
    const res = await fetch(`./data/fred_cache.json?v=${Date.now()}`);
    if (!res.ok) {
      throw new Error(`HTTP ${res.status} loading fred_cache.json`);
    }
    cacheBundle = await res.json();
    return cacheBundle;
  } catch (err) {
    console.error('Failed to load local FRED cache:', err);
    return null;
  }
}

/**
 * Retrieves raw observation array for a given internal indicator key.
 * @param {string} indicatorKey - Key defined in SERIES_IDS (e.g., 'vix', 'hy_spread').
 * @returns {Promise<Array>} Array of FRED observation objects { date, value }.
 */
export async function fetchFredSeries(indicatorKey) {
  const bundle = await loadFredCache();
  if (!bundle || !Array.isArray(bundle[indicatorKey])) {
    return [];
  }
  return bundle[indicatorKey];
}

/**
 * Returns the cache metadata (e.g., last updated timestamp) if present.
 * @returns {Promise<Object|null>}
 */
export async function getCacheMeta() {
  const bundle = await loadFredCache();
  return bundle?._meta || null;
}

/**
 * Filters out missing FRED values ('.') and converts observations to chart-ready {x, y} points.
 * @param {Array} observations - Raw FRED observation array.
 * @returns {Array<{x: string, y: number}>} Clean chronological data points.
 */
export function cleanSeriesData(observations) {
  if (!Array.isArray(observations)) return [];
  return observations
    .filter(obs => obs && obs.value !== '.' && !isNaN(parseFloat(obs.value)))
    .map(obs => ({ x: obs.date, y: parseFloat(obs.value) }));
}

/**
 * Extracts the most recent valid observation from a raw FRED series.
 * @param {Array} observations - Raw FRED observation array.
 * @returns {{date: string, value: number}|null}
 */
export function getLatestValidPoint(observations) {
  if (!Array.isArray(observations) || observations.length === 0) return null;
  for (let i = observations.length - 1; i >= 0; i--) {
    const obs = observations[i];
    if (obs && obs.value !== '.' && !isNaN(parseFloat(obs.value))) {
      return { date: obs.date, value: parseFloat(obs.value) };
    }
  }
  return null;
}
